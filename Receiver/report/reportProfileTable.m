function reportProfileTable(profiles, dataDir, outDir)
%REPORTPROFILETABLE Dynamics of the maneuver profiles, measured on the truth.
%   reportProfileTable(profiles, dataDir, outDir) reads the profile statistics
%   stored by the simulator (<dataDir>\FighterProfiles\Fighter_<name>_IMU_200Hz.mat,
%   field imu.profile.stats) and writes outDir\table_profiles.tex with, per
%   profile: normal load factor range, peak g onset, peak roll rate, angle of
%   attack range, altitude range, speed range, and the fraction of time with
%   the antenna below the horizon (inverted). Works for custom maneuvers too
%   (their row label is the profile name).

lab = containers.Map( ...
    {'baseline_cruise','turn','loop_pushover','break_gonset','jinking','rolls','splitS_immelmann','departure_spin'}, ...
    {'Baseline & level cruise','Turn & 9-g level turn','Loop & loop, push-over','Break & 2 breaks to 9 g', ...
     'Jinking & 6-g reversals','Rolls & aileron, snap-style','Split-S/Imm. & half loops','Departure & spin, recovery'});
if ~exist(outDir, 'dir'), mkdir(outDir); end
fid = fopen(fullfile(outDir, 'table_profiles.tex'), 'w');
fprintf(fid, '%% Maneuver profiles, dynamics measured on the truth (generated by reportProfileTable.m)\n');
for k = 1:numel(profiles)
    p = profiles{k};
    S = load(fullfile(dataDir, 'FighterProfiles', ['Fighter_' p '_IMU_200Hz.mat']));  st = S.imu.profile.stats;
    if isKey(lab, p), c = lab(p); else, c = [strrep(p, '_', '\_') ' & custom']; end
    fprintf(fid, '%s & %s & %s & %s & %s & %s & %s & %.0f\\\\\n', c, rangeStr(st.minNz, st.maxNz, '%.1f'), ...
        num(st.maxOnsetGps, '%.1f'), num(st.maxRollRate, '%.0f'), rangeStr(st.alphaRange(1), st.alphaRange(2), '%.1f'), ...
        rangeStr(st.hRange(1)/1e3, st.hRange(2)/1e3, '%.2f', '--'), rangeStr(st.VRange(1), st.VRange(2), '%.0f', '--'), ...
        100*st.invertedFrac);
end
fclose(fid);
type(fullfile(outDir, 'table_profiles.tex'));
end

function s = num(x, f)
% values below the last printed digit are written as 0 (level flight)
s = sprintf(f, x);
if str2double(s) < 0.5 && contains(f, '.1f') && x < 0.5, s = '0'; end
if strcmp(s, '-0'), s = '0'; end
s = neg(s);
end

function s = rangeStr(a, b, f, sep)
if nargin < 4, sep = '..'; end
sa = sprintf(f, a);  sb = sprintf(f, b);
if strcmp(sa, sb), s = neg(sa); else, s = [neg(sa) sep neg(sb)]; end
end

function s = neg(s)
if startsWith(s, '-'), s = ['$-' s(2:end) '$']; end
end
