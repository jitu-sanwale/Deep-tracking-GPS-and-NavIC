function reportTables(profiles, outDir, runDir)
%REPORTTABLES Result tables of the full test matrix and summary statistics.
%   reportTables(profiles, outDir) reads the receiver summaries
%     Receiver\output\results_FighterSummary{,_NavIC,_GPS_NavIC}\fighter_summary.csv
%   (written by summarizeFighterRuns.m) and writes to outDir
%     table_navic_alone.tex   - NavIC L5 alone, rms / max
%     table_gps_alone.tex     - GPS L1 alone, rms
%     table_navic_gps.tex     - NavIC L5 + GPS L1, rms, ISB, channels
%     results_statistics.txt  - ranges and medians over the seven maneuvers
rxDir = fileparts(fileparts(mfilename('fullpath')));
if nargin < 3 || isempty(runDir), runDir = fullfile(rxDir, 'output'); end
if ~exist(outDir, 'dir'), mkdir(outDir); end
G  = readSummary(fullfile(runDir, 'results_FighterSummary',           'fighter_summary.csv'));
N  = readSummary(fullfile(runDir, 'results_FighterSummary_NavIC',     'fighter_summary.csv'));
GN = readSummary(fullfile(runDir, 'results_FighterSummary_GPS_NavIC', 'fighter_summary.csv'));
lab = containers.Map( ...
    {'baseline_cruise','turn','loop_pushover','break_gonset','jinking','rolls','splitS_immelmann','departure_spin'}, ...
    {'Baseline','Turn','Loop','Break','Jinking','Rolls','Split-S/Imm.','Departure'});
modes = {'CT','VT','UT'};

% ---------------- NavIC alone, rms / max
fid = fopen(fullfile(outDir, 'table_navic_alone.tex'), 'w');
fprintf(fid, '%% NavIC L5 alone, maneuver-window 3-D rms / max (generated by reportTables.m)\n');
for i = 1:numel(profiles)
    p = profiles{i};  c = {lab(p)};
    for q = {'man_pos', 'man_vel'}
        for m = 1:3
            r = val(N, p, modes{m}, [q{1} '_rms_' unit(q{1})]);  x = val(N, p, modes{m}, [q{1} '_max_' unit(q{1})]);
            if isnan(r), c{end+1} = '--'; %#ok<AGROW>
            else
                s = sprintf('%s / %s', num(r), num(x));
                if m == 3 && i > 1, s = ['\textbf{' num(r) '} / ' num(x)]; end
                c{end+1} = s; %#ok<AGROW>
            end
        end
    end
    fprintf(fid, '%s\\\\\n', strjoin(c, ' & '));
end
fclose(fid);

% ---------------- GPS alone, rms
fid = fopen(fullfile(outDir, 'table_gps_alone.tex'), 'w');
fprintf(fid, '%% GPS L1 alone, maneuver-window 3-D rms (generated by reportTables.m)\n');
for i = 1:numel(profiles)
    p = profiles{i};  c = {lab(p)};
    for m = 1:3, c{end+1} = numk(val(G, p, modes{m}, 'man_pos_rms_m')); end %#ok<AGROW>
    for m = 1:3, c{end+1} = num(val(G, p, modes{m}, 'man_vel_rms_mps')); end %#ok<AGROW>
    fprintf(fid, '%s\\\\\n', strjoin(c, ' & '));
end
fclose(fid);

% ---------------- NavIC + GPS, rms, ISB, channels
fid = fopen(fullfile(outDir, 'table_navic_gps.tex'), 'w');
fprintf(fid, '%% NavIC L5 + GPS L1, maneuver-window 3-D rms, ISB error, UT channels (generated by reportTables.m)\n');
for i = 1:numel(profiles)
    p = profiles{i};  c = {lab(p)};
    for m = 1:3, c{end+1} = bf(num(val(GN, p, modes{m}, 'man_pos_rms_m')), m == 3 && i > 1); end %#ok<AGROW>
    for m = 1:3, c{end+1} = bf(num(val(GN, p, modes{m}, 'man_vel_rms_mps')), m == 3 && i > 1); end %#ok<AGROW>
    c{end+1} = sprintf('%.2f', val(GN, p, 'UT', 'man_isb_err_rms_m'));
    c{end+1} = sprintf('%.1f', val(GN, p, 'UT', 'man_chUsed'));
    fprintf(fid, '%s\\\\\n', strjoin(c, ' & '));
end
fclose(fid);

% ---------------- ranges and medians over the seven maneuvers
man = profiles(~strcmp(profiles, 'baseline_cruise'));
f = @(T, m, col) cellfun(@(p) val(T, p, m, col), man);
pN = f(N,'UT','man_pos_rms_m');  vN = f(N,'UT','man_vel_rms_mps');
pG = f(G,'UT','man_pos_rms_m');  vG = f(G,'UT','man_vel_rms_mps');
pGN = f(GN,'UT','man_pos_rms_m'); vGN = f(GN,'UT','man_vel_rms_mps');
isb = cellfun(@(p) val(GN, p, 'UT', 'man_isb_err_rms_m'), profiles);
red = 100*(1 - vGN./vG);
fid = fopen(fullfile(outDir, 'results_statistics.txt'), 'w');
out = @(varargin) fprintf(fid, varargin{:});
out('Statistics over the seven maneuvers (generated by reportTables.m)\n\n');
out('UT, NavIC alone      : position %.1f-%.1f m, velocity %.2f-%.2f m/s rms\n', min(pN), max(pN), min(vN), max(vN));
out('UT, NavIC + GPS      : position %.1f-%.1f m, velocity %.3f-%.3f m/s rms\n', min(pGN), max(pGN), min(vGN), max(vGN));
out('UT, GPS alone        : position %.1f-%.1f m, velocity %.3f-%.3f m/s rms\n', min(pG), max(pG), min(vG), max(vG));
out('NavIC+GPS vs GPS     : velocity reduction %.0f-%.0f%% (median %.0f%%), position ratio median %.2f\n', ...
    min(red), max(red), median(red), median(pGN./pG));
out('NavIC vs GPS (UT)    : position ratio %.1f-%.1f, velocity ratio %.1f-%.1f\n', min(pN./pG), max(pN./pG), min(vN./vG), max(vN./vG));
out('NavIC+GPS vs NavIC   : velocity factor %.0f-%.0f\n', min(vN./vGN), max(vN./vGN));
out('ISB error (UT, all 8): %.2f-%.2f m rms\n', min(isb), max(isb));
for m = {'CT','VT'}
    out('%s, NavIC alone      : position %s m, velocity %s m/s\n', m{1}, rng_(f(N,m{1},'man_pos_rms_m')), rng_(f(N,m{1},'man_vel_rms_mps')));
    out('%s, NavIC + GPS      : position %s m, velocity %s m/s\n', m{1}, rng_(f(GN,m{1},'man_pos_rms_m')), rng_(f(GN,m{1},'man_vel_rms_mps')));
    out('%s, GPS alone        : position %s m, velocity %s m/s\n', m{1}, rng_(f(G,m{1},'man_pos_rms_m')), rng_(f(G,m{1},'man_vel_rms_mps')));
end
fclose(fid);
type(fullfile(outDir, 'results_statistics.txt'));
fprintf('Tables written to %s\n', outDir);
end

% ------------------------------------------------------------------ helpers
function T = readSummary(fn)
if ~exist(fn, 'file'), error('reportTables: missing %s (run the receiver stage first)', fn); end
T = readtable(fn, 'TextType', 'string');
end
function v = val(T, p, m, col)
r = T.profile == p & T.mode == m;
if any(r) && ismember(col, T.Properties.VariableNames), v = T.(col)(find(r, 1)); else, v = NaN; end
if ~isfinite(v) || v > 1e6, v = NaN; end
end
function u = unit(q)
if strcmp(q, 'man_pos'), u = 'm'; else, u = 'mps'; end
end
function s = num(x)
if isnan(x), s = '--';
elseif x >= 100, s = sprintf('%.0f', x);
elseif x >= 10, s = sprintf('%.1f', x);
elseif x >= 1, s = sprintf('%.2f', x);
elseif x >= 0.1, s = sprintf('%.2f', x);
else, s = sprintf('%.3f', x);
end
end
function s = numk(x)
if x >= 1000, s = sprintf('%.1fk', x/1000); else, s = num(x); end
end
function s = bf(s, on)
if on, s = ['\textbf{' s '}']; end
end
function s = rng_(x)
x = x(isfinite(x));
if isempty(x), s = '--'; else, s = sprintf('%.3g-%.3g', min(x), max(x)); end
end
