function T = caseReport(resDir, caseLabel)
%CASEREPORT Results table of one processed data set (single case).
%
%   T = caseReport(resDir, caseLabel)
%
%   Reads <resDir>\truth_comparison_summary.csv (and isb_summary.csv for the
%   combined GPS + NavIC configuration), written by compareTruth for one
%   run, and writes in the same folder
%     case_table.md    3-D rms / max position and velocity error, horizontal
%                      and vertical rms error and channels used, for every
%                      receiver (CT, VT, UT) and evaluation window
%                      (all = whole common interval, event = maneuver
%                      window, post = after the maneuver)
%     case_table.tex   the maneuver-window rows as a LaTeX table body
%   The table is also printed to the command window.
%
%   Written for this package (J. Sanwale et al., 2026), GPL-3.0-or-later.

f = fullfile(resDir, 'truth_comparison_summary.csv');
if ~exist(f, 'file'), T = table(); fprintf(2, 'caseReport: no %s\n', f); return; end
T = readtable(f, 'TextType', 'string');
fi = fullfile(resDir, 'isb_summary.csv');
hasIsb = exist(fi, 'file') == 2;
if hasIsb
    I = readtable(fi, 'TextType', 'string');
    T = outerjoin(T, I(:, {'mode', 'window', 'isb_err_rms_m'}), 'Keys', {'mode', 'window'}, 'MergeKeys', true);
end
short = containers.Map({'Classical', 'Vector', 'Ultratight'}, {'CT', 'VT', 'UT'});
rx = arrayfun(@(m) short(extractBefore(m + " ", " ")), T.mode, 'UniformOutput', false);
% order: CT, VT, UT and windows all, event, post (the join above sorts the rows)
[~, ir] = ismember(rx, {'CT', 'VT', 'UT'});  [~, iw] = ismember(T.window, ["all", "event", "post"]);
[~, o] = sortrows([ir(:) iw(:)]);  T = T(o, :);  rx = rx(o);

% Markdown table, all windows
hdr = {'Receiver', 'Window', 'Pos. rms (m)', 'Pos. max (m)', 'Horiz. rms (m)', 'Vert. rms (m)', ...
       'Vel. rms (m/s)', 'Vel. max (m/s)', 'Channels'};
if hasIsb, hdr{end+1} = 'ISB err. rms (m)'; end
L = {['## ' caseLabel], '', ['| ' strjoin(hdr, ' | ') ' |'], ['|' repmat('---|', 1, numel(hdr))]};
for k = 1:height(T)
    v = [T.pos3D_rms_m(k), T.pos3D_max_m(k), T.horiz_rms_m(k), T.up_rms_m(k), T.vel3D_rms_mps(k), T.vel3D_max_mps(k)];
    row = [{rx{k}, char(T.window(k))}, arrayfun(@fmt, v, 'UniformOutput', false), {sprintf('%.1f', T.chUsed_mean(k))}];
    if hasIsb, row{end+1} = fmt(T.isb_err_rms_m(k)); end
    L{end+1} = ['| ' strjoin(row, ' | ') ' |']; %#ok<AGROW>
end
writelines(string(L), fullfile(resDir, 'case_table.md'));
fprintf('\n%s\n', strjoin(L, newline));

% LaTeX body, maneuver window only
ev = T.window == "event";
fid = fopen(fullfile(resDir, 'case_table.tex'), 'w');
fprintf(fid, '%% %s: maneuver-window error vs truth (generated by caseReport.m)\n', caseLabel);
fprintf(fid, '%% Receiver & pos. rms & pos. max & vel. rms & vel. max%s\\\\\n', repmat(' & ISB err. rms', 1, hasIsb));
for k = find(ev)'
    c = {rx{k}, fmt(T.pos3D_rms_m(k)), fmt(T.pos3D_max_m(k)), fmt(T.vel3D_rms_mps(k)), fmt(T.vel3D_max_mps(k))};
    if hasIsb, c{end+1} = fmt(T.isb_err_rms_m(k)); end
    fprintf(fid, '%s\\\\\n', strjoin(c, ' & '));
end
fclose(fid);
end

function s = fmt(x)
% three significant figures, thousands as k
if ~isfinite(x), s = 'n/a';
elseif abs(x) >= 1e4, s = sprintf('%.1fk', x/1e3);
elseif abs(x) >= 100, s = sprintf('%.0f', x);
else, s = sprintf('%.3g', x);
end
end
