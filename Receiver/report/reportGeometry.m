function G = reportGeometry(runDir, dataDir, outDir)
%REPORTGEOMETRY NavIC satellite geometry table and dilutions of precision.
%   G = reportGeometry(runDir, dataDir, outDir) uses the ephemerides the
%   receiver decoded from the baseline GPS + NavIC data set
%     <runDir>\eph_gps_0IF_Fs5MHz_8bit_IQ_Fighter_baseline_cruise_GPS_NavIC.mat
%     <runDir>\nAcquired_..._baseline_cruise_GPS_NavIC.mat   (satellites in view)
%     <runDir>\sbf_..._baseline_cruise_GPS_NavIC.mat         (start-of-data time)
%   and the start of the truth trajectory (<dataDir>\FighterProfiles\
%   Fighter_baseline_cruise.csv), and writes to outDir
%     table_navic_satellites.tex  - PRN, orbit, elevation/azimuth, range, inclination
%     geometry_dop.txt            - PDOP / VDOP: NavIC alone, GPS alone, GPS + NavIC (with ISB state)

tag = 'gps_0IF_Fs5MHz_8bit_IQ_Fighter_baseline_cruise_GPS_NavIC';
E = load(fullfile(runDir, ['eph_' tag '.mat']));  eph = E.eph;
A = load(fullfile(runDir, ['nAcquired_' tag '.mat']));  sv = A.nAcquired.sv;
B = load(fullfile(runDir, ['sbf_' tag '.mat']));  sbf = B.sbf;
tr = readmatrix(fullfile(dataDir, 'FighterProfiles', 'Fighter_baseline_cruise.csv'), 'NumHeaderLines', 1);
if ~exist(outDir, 'dir'), mkdir(outDir); end

% receiver position and time at the start of the data
d2r = pi/180;  lat = tr(1,2)*d2r;  lon = tr(1,3)*d2r;  h = tr(1,4);
a = 6378137;  e2 = 6.69437999014e-3;  N = a/sqrt(1 - e2*sin(lat)^2);
r0 = [(N + h)*cos(lat)*cos(lon); (N + h)*cos(lat)*sin(lon); (N*(1 - e2) + h)*sin(lat)];
Cen = [-sin(lon) cos(lon) 0; -sin(lat)*cos(lon) -sin(lat)*sin(lon) cos(lat); cos(lat)*cos(lon) cos(lat)*sin(lon) sin(lat)];
ref = sv(find(sv < 100, 1));
skip = 0.1;                                       % file.skip of initParameters.m [s]
t0 = eph(ref).TOW1(1) - sbf.sfb1(ref)*0.02 - skip; % GPS time of week of the first sample

nS = numel(sv);  U = zeros(nS, 3);  el = zeros(nS,1);  az = el;  rng = el;
for k = 1:nS
    rs = svPosVel(sv(k), eph, t0 - 0.075, 1);       % ~75 ms signal travel time
    w = 7.2921151467e-5*0.075;                        % Earth rotation during travel
    rs = [cos(w) sin(w) 0; -sin(w) cos(w) 0; 0 0 1]*rs(:);
    d = rs - r0;  rng(k) = norm(d);  U(k,:) = d'/rng(k);
    enu = Cen*d;  el(k) = asin(enu(3)/rng(k))/d2r;  az(k) = mod(atan2(enu(1), enu(2))/d2r, 360);
end
isN = sv > 100;
Gn  = [-U(isN,:) ones(nnz(isN),1)];
Gg  = [-U(~isN,:) ones(nnz(~isN),1)];
Ggn = [-U ones(nS,1) double(isN(:))];              % common clock + GPS-NavIC inter-system bias
G.navic = [pdop(Gn) vdop(Gn, Cen)];  G.gps = [pdop(Gg) vdop(Gg, Cen)];  G.both = [pdop(Ggn) vdop(Ggn, Cen)];
G.prn = sv;  G.el = el;  G.az = az;  G.range = rng;

% NavIC satellite table
fid = fopen(fullfile(outDir, 'table_navic_satellites.tex'), 'w');
fprintf(fid, '%% NavIC satellites at the start of the data (generated by reportGeometry.m)\n');
for k = find(isN(:))'
    prn = sv(k) - 100;  inc = eph(sv(k)).i0(1)/d2r;
    if inc < 10, orb = 'GSO'; else, orb = 'IGSO'; end
    rkm = sprintf('%d', round(rng(k)/1e3));  rkm = [rkm(1:end-3) '\,' rkm(end-2:end)];
    fprintf(fid, '%d & %s & %.1f / %.1f & %s & %.1f\\\\\n', prn, orb, el(k), az(k), rkm, inc);
end
fclose(fid);
fid = fopen(fullfile(outDir, 'geometry_dop.txt'), 'w');
fprintf(fid, 'Geometry at the start of the data (GPS TOW %.1f s), %d GPS + %d NavIC satellites\n', t0, nnz(~isN), nnz(isN));
fprintf(fid, '  NavIC alone : PDOP %.2f  VDOP %.2f\n', G.navic);
fprintf(fid, '  GPS alone   : PDOP %.2f  VDOP %.2f\n', G.gps);
fprintf(fid, '  GPS + NavIC : PDOP %.2f  VDOP %.2f  (with the inter-system-bias state)\n', G.both);
fclose(fid);
type(fullfile(outDir, 'geometry_dop.txt'));
end

function p = pdop(Gm)
Q = inv(Gm'*Gm);  p = sqrt(trace(Q(1:3,1:3)));
end

function v = vdop(Gm, Cen)
Q = inv(Gm'*Gm);  Qe = Cen*Q(1:3,1:3)*Cen';  v = sqrt(Qe(3,3));
end
